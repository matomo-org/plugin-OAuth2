namespace Piwik\Plugins\OAuth2\Service;

use Piwik\Log\LoggerInterface;
use Piwik\Option;
use Piwik\SettingsPiwik;

/**
 * Writes the authorization server metadata (RFC 8414) as a static file at
 * <document root>/.well-known/oauth-authorization-server.
 *
 * Every web server serves an existing file without further configuration, so on root installs
 * clients can discover the authorization server without a rewrite rule forwarding the path to
 * the metadata controller action. Subdirectory installs are skipped, as RFC 8414 places their
 * discovery URL at the domain root, outside the Matomo directory.
 *
 * The file is a snapshot, so it is written again whenever its content may change. Files that
 * were not written by this class are never overwritten or removed.
 */
class DiscoveryFile
{
    public const STATUS_WRITTEN = 'written';
    public const STATUS_UNCHANGED = 'unchanged';
    public const STATUS_SKIPPED_NO_URL = 'skipped_no_url';
    public const STATUS_SKIPPED_SUBDIRECTORY = 'skipped_subdirectory';
    public const STATUS_SKIPPED_FOREIGN_FILE = 'skipped_foreign_file';
    public const STATUS_NOT_WRITABLE = 'not_writable';

    public const DIRECTORY = '.well-known';
    public const FILE_NAME = 'oauth-authorization-server';

    /**
     * Hash of the last file content written, which identifies the file as written by this class.
     */
    public const OPTION_FILE_HASH = 'OAuth2.discoveryFileHash';

    /**
     * Marks the helper files below as generated, so they are only replaced or removed when they are.
     */
    private const MARKER = 'Generated by the Matomo OAuth2 plugin';

    public function __construct(
        private AuthorizationServerMetadata $metadata,
        private LoggerInterface $logger,
        private string $documentRoot = PIWIK_DOCUMENT_ROOT
    ) {
    }

    /**
     * Writes the metadata file, or updates it when its content changed.
     *
     * @param bool $force Also replace a file this class did not write.
     * @return string One of the STATUS_* constants.
     */
    public function write(bool $force = false): string
    {
        $issuer = $this->getIssuer();
        if ($issuer === null) {
            return self::STATUS_SKIPPED_NO_URL;
        }

        if ((string) parse_url($issuer, PHP_URL_PATH) !== '') {
            return self::STATUS_SKIPPED_SUBDIRECTORY;
        }

        $path = $this->getFilePath();
        $content = (string) json_encode($this->metadata->build($issuer), JSON_UNESCAPED_SLASHES);
        $hash = sha1($content);

        if (file_exists($path)) {
            $existingHash = sha1((string) @file_get_contents($path));

            if ($existingHash === $hash) {
                // A file with the same content that Matomo did not write stays somebody else's.
                if ($existingHash === Option::get(self::OPTION_FILE_HASH)) {
                    $this->writeHelperFiles();
                }
                return self::STATUS_UNCHANGED;
            }

            if (!$force && $existingHash !== Option::get(self::OPTION_FILE_HASH)) {
                $this->logger->info('OAuth2: {path} was not written by Matomo, so it is not updated.', ['path' => $path]);
                return self::STATUS_SKIPPED_FOREIGN_FILE;
            }
        }

        $directory = $this->getDirectoryPath();
        if (
            (!is_dir($directory) && !@mkdir($directory, 0755))
            || !$this->writeFile($path, $content)
        ) {
            $this->logger->info('OAuth2: Could not write {path}, the discovery endpoint needs a web server rule instead.', ['path' => $path]);
            return self::STATUS_NOT_WRITABLE;
        }

        $this->rememberHash($hash);
        $this->writeHelperFiles();

        return self::STATUS_WRITTEN;
    }

    /**
     * Removes the metadata file and its helper files, if they were written by this class.
     */
    public function remove(): void
    {
        $path = $this->getFilePath();

        if (
            file_exists($path)
            && sha1((string) @file_get_contents($path)) === Option::get(self::OPTION_FILE_HASH)
            && !@unlink($path)
        ) {
            // Keep the hash, so the file left behind is still recognised as written by Matomo.
            $this->logger->info('OAuth2: Could not remove {path}.', ['path' => $path]);
            return;
        }

        Option::delete(self::OPTION_FILE_HASH);

        foreach (['.htaccess', 'web.config'] as $helperFile) {
            $helperPath = $this->getDirectoryPath() . '/' . $helperFile;
            if ($this->isGenerated($helperPath)) {
                @unlink($helperPath);
            }
        }

        // Only succeeds when empty, so a directory also used for other well-known URIs is kept.
        if (is_dir($this->getDirectoryPath())) {
            @rmdir($this->getDirectoryPath());
        }
    }

    /**
     * Returns the issuer the file is written for, the stored Matomo URL without trailing slash.
     *
     * Read from the option rather than SettingsPiwik::getPiwikUrl(), which during a web request
     * returns the host of that request, so the file doesn't depend on where it was written from.
     */
    public function getIssuer(): ?string
    {
        $url = rtrim((string) Option::get(SettingsPiwik::OPTION_PIWIK_URL), '/');

        return $url === '' ? null : $url;
    }

    public function getFilePath(): string
    {
        return $this->getDirectoryPath() . '/' . self::FILE_NAME;
    }

    private function getDirectoryPath(): string
    {
        return rtrim($this->documentRoot, '/') . '/' . self::DIRECTORY;
    }

    private function rememberHash(string $hash): void
    {
        Option::set(self::OPTION_FILE_HASH, $hash);
    }

    /**
     * Writes to a temporary file first, so a request never gets a partially written document.
     */
    private function writeFile(string $path, string $content): bool
    {
        $temporaryPath = $path . '.' . uniqid('', true) . '.tmp';

        if (@file_put_contents($temporaryPath, $content) === false) {
            return false;
        }

        @chmod($temporaryPath, 0644);

        if (!@rename($temporaryPath, $path)) {
            @unlink($temporaryPath);
            return false;
        }

        return true;
    }

    /**
     * Without these, Apache sends the extensionless file without a JSON content type and IIS
     * refuses to serve it at all. nginx needs no helper file and ignores both.
     */
    private function writeHelperFiles(): void
    {
        $this->writeHelperFile('.htaccess', $this->getHtaccessContent());
        $this->writeHelperFile('web.config', $this->getWebConfigContent());
    }

    private function writeHelperFile(string $fileName, string $content): void
    {
        $path = $this->getDirectoryPath() . '/' . $fileName;

        if (file_exists($path) && !$this->isGenerated($path)) {
            $this->logger->info('OAuth2: {path} was not written by Matomo, so it is not updated.', ['path' => $path]);
            return;
        }

        $this->writeFile($path, $content);
    }

    private function isGenerated(string $path): bool
    {
        return file_exists($path) && strpos((string) @file_get_contents($path), self::MARKER) !== false;
    }

    /**
     * Deliberately no rewrite to the metadata action: Matomo stores the URL of each dispatched
     * request as its own URL, which for a rewritten discovery request is <host>/.well-known/.
     */
    private function getHtaccessContent(): string
    {
        return '# ' . self::MARKER . ', do not edit directly.' . "\n"
            . '<Files "' . self::FILE_NAME . '">' . "\n"
            . '    <IfModule mod_mime.c>' . "\n"
            . '        ForceType application/json' . "\n"
            . '    </IfModule>' . "\n"
            . '</Files>' . "\n";
    }

    private function getWebConfigContent(): string
    {
        return '<?xml version="1.0" encoding="UTF-8"?>' . "\n"
            . '<!-- ' . self::MARKER . ', do not edit directly. -->' . "\n"
            . '<configuration>' . "\n"
            . '  <location path="' . self::FILE_NAME . '">' . "\n"
            . '    <system.webServer>' . "\n"
            . '      <staticContent>' . "\n"
            . '        <remove fileExtension="." />' . "\n"
            . '        <mimeMap fileExtension="." mimeType="application/json" />' . "\n"
            . '      </staticContent>' . "\n"
            . '    </system.webServer>' . "\n"
            . '  </location>' . "\n"
            . '</configuration>' . "\n";
    }
}
